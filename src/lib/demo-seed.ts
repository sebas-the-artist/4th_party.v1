function finishRun(input: {
  workspace: Workspace;
  location: Location;
  runId: string;
  periodStart: string;
  periodEnd: string;
  createdAt: string;
}) {
  const { workspace, location, runId, createdAt } = input;
  const locationSourcesList = workspace.sources.filter((source) => source.locationId === location.id);
  const matches = runMatchingEngine({
    runId,
    locationId: location.id,
    location,
    contact: workspace.contact,
    sources: locationSourcesList,
    posOrders: workspace.posOrders.filter((row) => row.locationId === location.id),
    deliveryItems: workspace.deliveryItems.filter((row) => row.locationId === location.id),
    bankDeposits: workspace.bankDeposits.filter((row) => row.locationId === location.id),
  });

  const netVarianceCents = matches
    .filter((match) => match.status !== "matched")
    .reduce((total, match) => total + match.varianceCents, 0);

  workspace.runs.push({
    id: runId,
    locationId: location.id,
    periodStart: input.periodStart,
    periodEnd: input.periodEnd,
    status: "complete",
    netVarianceCents,
    createdAt,
  });
  workspace.matches.push(...matches);
  workspace.disputes.push(
    ...matches
      .filter((match) => match.status !== "matched")
      .map((match) => ({
        id: `dsp_${match.id}`,
        matchId: match.id,
        runId,
        locationId: location.id,
        status: "ready" as const,
        subject: disputeSubject(match.disputeText),
        body: match.disputeText,
        toEmail: supportEmailFor(locationSourcesList, match.platform),
        updatedAt: createdAt,
      })),
  );
}

